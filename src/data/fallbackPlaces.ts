/**
 * Acil durum verisi için mesafe sınırı: seçilen merkezden daha uzaktaki
 * (örn. başka şehirdeki) mekanlar ASLA gösterilmez.
 */
export const MAX_FALLBACK_DISTANCE_M = 35000;

/** Küçük haversine (osm.ts ile döngüsel import yaratmamak için burada). */
function haversine(
  a: Coordinates,
  b: { lat: number; lon: number },
): number {
  const R = 6371000;
  const dLat = ((b.lat - a.lat) * Math.PI) / 180;
  const dLon = ((b.lon - a.lon) * Math.PI) / 180;
  const la1 = (a.lat * Math.PI) / 180;
  const la2 = (b.lat * Math.PI) / 180;
  const h =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(la1) * Math.cos(la2) * Math.sin(dLon / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h));
}

/**
 * KESİN kategori acil durum filtresi. Kullanıcı hangi kategoriyi
 * seçtiyse YALNIZCA o kategoriye ait mekanlar döner. "Listeyi
 * doldurmak için başka kategori yapıştırma" KESİNLİKLE YAPILMAZ.
 * 20 km mesafe sınırı da uygulanır; uzak şehirler asla görünmez.
 */
export function filterFallbackPlaces(opts: {
  center?: Coordinates;
  categoryIds?: string[];
  limit?: number;
}): Place[] {
  const limit = opts.limit ?? 20;

  let list = FALLBACK_PLACES.filter((p) => {
    if (!opts.center) return true;
    return (
      haversine(opts.center, { lat: p.latitude, lon: p.longitude }) <=
      MAX_FALLBACK_DISTANCE_M
    );
  });

  if (opts.categoryIds?.length) {
    list = list.filter((p) => opts.categoryIds!.includes(p.categoryId));
  }

  return list.slice(0, limit);
}

/**
 * Bölgesel popüler mekanlar: seçili kategoride 0 sonuç olduğunda
 * "öneri yok" ekranı yerine gösterilen son güvence. Merkez 35 km
 * içindeki bilinen popüler noktalar (Seka Park, Ormanya, Kartepe,
 * Başiskele Sahil vb.) döner.
 */
export function popularRegionalPlaces(opts: {
  center?: Coordinates;
  limit?: number;
}): Place[] {
  const limit = opts.limit ?? 12;
  let list = FALLBACK_PLACES.filter((p) => {
    if (!opts.center) return true;
    return (
      haversine(opts.center, { lat: p.latitude, lon: p.longitude }) <=
      MAX_FALLBACK_DISTANCE_M
    );
  });
  return list.slice(0, limit);
}

/** Kullanıcı konumuna göre acil durum listesini mesafeye göre sıralar. */
export function sortFallbackByDistance(
  places: Place[],
  center: Coordinates,
  haversine: (a: Coordinates, b: { lat: number; lon: number }) => number,
): Place[] {
  return places
    .map((p) => ({
      ...p,
      distanceMeters: haversine(center, { lat: p.latitude, lon: p.longitude }),
    }))
    .sort((a, b) => (a.distanceMeters ?? 0) - (b.distanceMeters ?? 0));
}
